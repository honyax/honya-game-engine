namespace SoftwareRasterizer;

/// <summary>
/// 深度バッファ(Zバッファ)。
///
/// フレームバッファが「そのピクセルは何色か」を覚えているのに対して、
/// こちらは**「そのピクセルに今描かれているものは、どれくらい手前にあるか」**を覚えている。
/// 画面と同じ解像度の float 配列がもう1枚あるだけ、というのが実体。
///
/// この1枚を足すだけで、Day 6 の画家のアルゴリズムが抱えていた問題
/// (交差する三角形、循環する重なり、ソートのコスト)が**まとめて消える**。
/// 三角形を描く順序が完全に自由になり、1枚描くごとの判断だけで前後関係が決まる。
/// アイデアの単純さに対して効果が大きい、グラフィックス史上でも屈指の発明。
///
/// 代償はメモリ。640x480 でも float なら 1.2MB で、
/// 1970年代には「画面と同じ大きさのバッファをもう1枚」が現実的でなかった。
/// メモリが安くなったからZバッファが標準になった、という面がある。
/// </summary>
internal sealed class DepthBuffer
{
    public int Width { get; }

    public int Height { get; }

    /// <summary>
    /// 深度値の配列。中身は NDC の Z(0 = 近クリップ面、1 = 遠クリップ面)。
    ///
    /// なぜ「カメラからの距離」ではなく NDC の Z を入れるのか:
    /// **透視除算を済ませた後の Z は、画面上で線形に変化する**から。
    /// 三角形の3頂点の値をバリセントリック座標で補間するだけで、
    /// 内部の任意のピクセルの正しい深度が得られる。
    /// カメラからの距離そのものを補間すると、遠近感のぶん歪んで間違った値になる
    /// (この歪みの問題は Day 8 のテクスチャで正面から扱うことになる)。
    /// </summary>
    public float[] Depth { get; }

    public DepthBuffer(int width, int height)
    {
        Width = width;
        Height = height;
        Depth = new float[width * height];
    }

    /// <summary>
    /// 全体を「無限に遠い」状態にリセットする。毎フレームの描画前に必ず呼ぶ。
    ///
    /// 1.0 は遠クリップ面の深度。ここを初期値にしておくと、
    /// 「まだ何も描かれていない場所」は常に負けるので、最初の1枚が必ず通る。
    /// **これを忘れると、前のフレームの深度が残って絵が虫食いになる**。
    /// 症状が独特(物体の一部が透明に抜ける)なので、見たら真っ先にここを疑うとよい。
    /// </summary>
    public void Clear() => Array.Fill(Depth, 1.0f);
}
