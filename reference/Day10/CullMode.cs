namespace SoftwareRasterizer;

/// <summary>
/// 背面カリングの設定。どちら向きの面を捨てるか。
///
/// 閉じた立体では、裏を向いた面は必ず表の面に隠れて見えない。
/// **見えないと分かっているものを、描く前に捨てる**のがカリングで、
/// 判定は三角形1枚につき符号1つを見るだけと極端に安い。
/// 深度テストでも結果は正しくなるが、そちらは「塗ってから捨てる」ので無駄が大きい。
/// </summary>
internal enum CullMode
{
    /// <summary>カリングしない。板ポリゴンなど、裏からも見せたいものに使う。</summary>
    None,

    /// <summary>裏を向いた面を捨てる(通常はこれ)。</summary>
    Back,

    /// <summary>表を向いた面を捨てる。物体の内側を見せたいときなどに使う。</summary>
    Front,
}
