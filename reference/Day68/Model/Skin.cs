using System.Numerics;

namespace HonyaEngine;

/// <summary>
/// スキン1つ(Day 41)。**「どのノードが関節か」と「バインドポーズをどう打ち消すか」**。
///
/// <para>
/// <b>スキニングの式は1行しかない</b>。頂点の最終位置は
/// <code>
///   p' = Σ w[i] * ( IBM[j[i]] * world(joint[j[i]]) ) * p
/// </code>
/// で、括弧の中を**関節行列**と呼ぶ。今日やることの全部がこの式に入っている。
/// </para>
///
/// <para>
/// <b>なぜ逆バインド行列(IBM)が要るのか</b>。ここが最初の引っかかりどころ。
///
/// 頂点 <c>p</c> はメッシュの座標系で書かれている。一方 <c>world(joint)</c> は
/// 「その関節が今どこにあるか」なので、掛けるといきなり
/// **メッシュを関節の位置へ丸ごと運んでしまう**。
///
/// 欲しいのは「バインドポーズからの差分」だけ。だから先に
/// <c>IBM = inverse(バインドポーズでの関節の世界行列)</c> を掛けて
/// **頂点を関節のローカル座標系へ持っていく**。
/// そのうえで今の世界行列を掛けると、関節が動いたぶんだけ頂点が動く。
///
/// 確かめ方: <b>バインドポーズでは <c>IBM * world(joint) = 単位行列</c> になる</b>。
/// つまり関節を1本も動かしていなければ、頂点は1ミリも動かない。
/// スキニングが壊れたとき、まずここを見る(Alt+F12 の自己チェックがこれを測る)。
/// </para>
///
/// <para>
/// <b>joints の並びが「関節の番号」を決める</b>。頂点の <c>JOINTS_0</c> に入っているのは
/// ノード番号ではなく、**この配列の添字**。
/// ノード番号だと 26 個のノードのうち 24 個が関節、のような疎な番号になり、
/// シェーダへ送る行列の配列が無駄に長くなるため、スキンごとに詰め直してある。
/// </para>
/// </summary>
/// <param name="Name">スキン名。デバッグ表示用。</param>
/// <param name="Joints">関節のノード番号。**この配列の添字が JOINTS_0 の値**。</param>
/// <param name="InverseBindMatrices">
/// 関節ごとの逆バインド行列。<paramref name="Joints"/> と同じ長さで、同じ順に並ぶ。
///
/// 省略されているファイルもあり、その場合は仕様上「全部単位行列」。
/// メッシュと関節が同じ座標系にある(= バインドポーズが原点)という意味になる。
/// </param>
/// <param name="SkeletonRoot">
/// 骨格の根ノード。-1 なら指定なし。
///
/// **描画には要らない**。関節行列は関節ごとの世界行列から作るので、
/// 根がどれかを知らなくても計算できる。用途は「このスキンだけを別の場所に置きたい」
/// といったときの取っ手で、今日は表示に出すだけ。
/// </param>
internal readonly record struct Skin(
    string Name,
    int[] Joints,
    Matrix4x4[] InverseBindMatrices,
    int SkeletonRoot)
{
    public int JointCount => Joints.Length;
}
